/**
 * Сфера контексту для запиту помічника.
 *
 * Проблема: до кожного запиту прикріплюється повний набір даних CRM.
 * На великому CRM це зайве навантаження для звичайної розмови (привітання,
 * короткі репліки, жарт) і може перевищувати контекст самої моделі.
 *
 * Розв'язання: коротке спілкування без даних CRM (числа, назви, запити)
 * отримує легкий контекст (підсумки балансів налаштувань); будь-який
 * намір, пов'язаний із даними CRM, завжди отримує повний контекст.
 */

/** Слова, які однозначно вказують на запит по даних CRM (укр/рос/англ або переклад). */
const CRM_SIGNAL =
  /(про[еє]кт|клі[єе]нт|тран[зс]акц|ф[іи]нан|б[юь]дж|доход|зароб|витрат|оплат|плат[іи]ж|б[оо]рг|рахун|банк|валют|курс|конвертац|[хх]остинг|хост|доплат|передоплат|накопич|депозит|сбереж|спец|виконав|партнер|зв[іи]т|м[іи]сяц|тижн|[рр]ік|рок|року|підсумк|ск[іи]льк|котр[ая]|балан|актив|грош|грив|долар|[єе]вро|usd|uah|eur|usdt|salary|invoice|payment|client|project|budget|income|expense|debt|banki|запиш|створи|добав|додай|видал|зміни|онови|чернетк|скопію|копіюй|перепиши|переказ|переведи|повтори про|оформ|списа)/i;

/** Ознака даних CRM у повідомленні: цифри або слова-сигнали про запис. */
function touchesCrm(text: string): boolean {
  const t = (text || '').trim();
  return !!t && (/\d/.test(t) || CRM_SIGNAL.test(t));
}

/**
 * Чи запит поводиться як звичайна розмова без даних CRM.
 * Легкий контекст — тільки коли запит короткий, без цифр і без
 * ознак даних CRM: привітання, репліки, побажання. Уточнення answers
 * перевіряється на рівні маршруту (продовження чернетки → повний контекст).
 *
 * Історія: короткі продовження на кшталт «а по ньому?» не містять
 * сигналів, але стосуються запису з попередніх реплік. Якщо останні
 * повідомлення розмови торкалися даних CRM — запит лишається на
 * повному контексті.
 */
export function isLightScope(text: string, history?: { role?: string; text?: string }[]): boolean {
  const t = (text || '').trim();
  if (!t || t.length > 120) return false;
  if (/\d/.test(t)) return false;
  if (CRM_SIGNAL.test(t)) return false;
  const recent = (history || []).slice(-6);
  if (recent.some(m => typeof m.text === 'string' && touchesCrm(m.text))) return false;
  return true;
}
